function getTileImages(originalUrl?: string, enhancedUrl?: string) {
  // Reject non-image / product-download OData endpoints or missing mock paths
  let cleanOriginal = originalUrl;
  if (
    cleanOriginal &&
    (cleanOriginal.includes("catalogue.dataspace.copernicus.eu") ||
      cleanOriginal.includes("$value") ||
      cleanOriginal.includes("thumbnail_") ||
      cleanOriginal === "/mock/original.png")
  ) {
    cleanOriginal = undefined;
  }

  const original = cleanOriginal
    ? resolveMediaUrl(cleanOriginal)
    : "/images/sample-lr-clean.jpeg";

  // INTERCEPT: Convert backend GeoTIFF path to browser-friendly PNG preview path
  let displayEnhancedUrl = enhancedUrl;
  if (displayEnhancedUrl && displayEnhancedUrl.endsWith(".tif")) {
    displayEnhancedUrl = displayEnhancedUrl
      .replace("/data/geotiffs/", "/previews/")
      .replace(".tif", ".png");
  }

  const enhanced = displayEnhancedUrl && displayEnhancedUrl !== "/mock/enhanced.png"
    ? resolveMediaUrl(displayEnhancedUrl)
    : "/images/sample-sr-clean.jpeg";

  return { original, enhanced };
}

